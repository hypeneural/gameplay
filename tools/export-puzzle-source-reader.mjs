import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const toolsDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(toolsDirectory, '..');
const outputPath = join(repositoryRoot, 'docs', 'references', 'PUZZLE_SWAP_CORE_SOURCES.txt');

const sourcePaths = [
  'apps/play/src/app/GameQuality.ts',
  'apps/play/src/app/AppRouter.tsx',
  'apps/play/src/phaser/createGame.ts',
  'apps/play/src/phaser/PhaserHost.tsx',
  'packages/platform/src/game-runtime/GameRunController.ts',
  'packages/platform/src/game-runtime/SceneScope.ts',
  'packages/games/puzzle-swap/src/domain/PuzzleBoard.ts',
  'packages/games/puzzle-swap/src/domain/PuzzleShuffle.ts',
  'packages/games/puzzle-swap/src/domain/PuzzleProgress.ts',
  'packages/games/puzzle-swap/src/domain/Swap.ts',
  'packages/games/puzzle-swap/src/domain/GridPlanner.ts',
  'packages/games/puzzle-swap/src/domain/IdleAssist.ts',
  'packages/theme/src/game-feel/FeedbackDirector.ts',
  'packages/theme/src/game-feel/ChristmasEffects.ts',
  'packages/theme/src/game-feel/EffectPolicy.ts',
  'packages/theme/src/game-feel/MotionTokens.ts',
  'packages/games/puzzle-swap/src/tuning.ts',
  'packages/games/puzzle-swap/src/runtime/phaser/audioAssets.ts',
  'packages/games/puzzle-swap/src/runtime/phaser/createPuzzleSwapGame.ts',
];

const sections = await Promise.all(
  sourcePaths.map(async (sourcePath) => {
    const source = await readFile(join(repositoryRoot, sourcePath), 'utf8');
    return [`${'='.repeat(96)}`, `SOURCE: ${sourcePath}`, '-'.repeat(96), source.trimEnd()].join(
      '\n',
    );
  }),
);

const header = [
  'PUZZLE SWAP — CORE SOURCE READER',
  'Generated by tools/export-puzzle-source-reader.mjs. Do not edit this copy directly.',
  'Canonical files are listed below. This reader contains no customer media, names or source paths.',
  '',
].join('\n');

await writeFile(outputPath, `${header}${sections.join('\n\n')}\n`, 'utf8');
